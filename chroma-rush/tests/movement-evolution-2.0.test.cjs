const test=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const {DASH,GAME}=require('../src/core/config.js');
const {ContextualDash}=require('../src/gameplay/contextual-dash.js');
const {PlayerMotion}=require('../src/render/player-motion.js');
const {MovementAwareness}=require('../src/director/movement-awareness.js');
