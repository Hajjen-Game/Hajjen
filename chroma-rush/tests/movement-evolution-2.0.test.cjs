test('air dash is gated, one per airborne interval, and never teleports',()=>{
  const d=new ContextualDash();
  assert.equal(d.request({zone:1,grounded:true}),null);
  assert.equal(DASH.unlockZone,1,'Dash is available immediately for real-device testing');
  assert.equal(d.request({zone:4,grounded:true}),null);
  assert.equal(d.request({zone:1,grounded:false}), 'air');
  const step=d.tick(1/60,500);
  assert.ok(step>0&&step<20);
  assert.equal(d.request({zone:4,grounded:false}),null);
  let extra=step;
  for(let i=0;i<30;i++)extra+=d.tick(1/60,500);
  assert.ok(extra>135&&extra<190,'Dash 2.2 has a noticeable but finite forward surge');
  assert.equal(d.request({zone:4,grounded:false}),null,'cannot farm two air dashes');
  d.onLand();
  assert.equal(d.request({zone:4,grounded:false}),'air','fresh landing restores air dash');
});
test('ground dash needs a SECOND separate press during an existing duck',()=>{
  const d=new ContextualDash();
  assert.equal(d.request({zone:4,grounded:true,ducking:false}),null);
  d.onDuckStart();
  assert.equal(d.request({zone:4,grounded:true,ducking:true}),'ground');
  assert.equal(d.request({zone:4,grounded:true,ducking:true}),null);
  d.tick(.25,500);
  assert.equal(d.request({zone:4,grounded:true,ducking:true}),null);
  d.onDuckEnd();
  d.onDuckStart();
  assert.equal(d.request({zone:4,grounded:true,ducking:true}),'ground');
  d.onDuckEnd();
  assert.equal(d.active,false);
});
test('dash cannot start during damage recovery or gravity shift',()=>{
  const d=new ContextualDash();
  assert.equal(d.request({zone:5,grounded:false,recovering:true}),null);
  assert.equal(d.request({zone:5,grounded:false,shifting:true}),null);
  assert.equal(d.request({zone:5,grounded:false}),'air');
  d.cancel();
  assert.equal(d.active,false);
});
test('air and duck motion stretch visually without modifying hitbox or gravity',()=>{
  const m=new PlayerMotion();
  const p={x:310,feet:515,vy:-400,landed:false,duck:false};
  const collision=playerBox(p);
  const before=m.sample({landed:false,vy:-400});
  m.dashStart(false);
  m.tick(.12);
  const during=m.sample({landed:false,vy:-400});
  assert.ok(during.scaleX>before.scaleX);
  assert.deepEqual(playerBox(p),collision);
  assert.equal(GAME.gravity,2140);
  m.duckStart();m.dashStart(true);m.tick(.12);
  const crouch=m.sample({landed:true,duck:true});
  assert.ok(crouch.scaleX>1.1);
  assert.ok(crouch.glow>.35);
});
test('the Director observes dash as player intent without forcing an obstacle',()=>{
  const m=new MovementAwareness();
  m.onDash('air',2);m.onDash('ground',3);
  assert.deepEqual(m.insight.dashUses,{air:1,ground:1});
  assert.ok(m.recoveryUntil>=3.38);
  const d=new AdaptiveRushDirector(()=>.5);
  const before=d.totalSpawned;
  d.noteDash('air');
  assert.equal(d.totalSpawned,before);
  assert.equal(d.movement.insight.dashUses.air,1);
});
