export function createRaceTelemetry(){
 const events=[];
 return Object.freeze({events,reset(){events.length=0},record(flight,kind,properties={}){
  events.push({type:kind,s:Math.round(flight.s),t:+flight.elapsed.toFixed(3),...properties});
 }});
}
export function downloadRaceAudit(data,preset,{Blob,URL,document,setTimeout}){
 const blob=new Blob([JSON.stringify(data,null,2)],{type:"application/json"});
 const url=URL.createObjectURL(blob),a=document.createElement("a");
 a.href=url;a.download="skyshift-v01348-performance-"+preset+"-audit.json";
 document.body.appendChild(a);a.click();a.remove();
 setTimeout(()=>URL.revokeObjectURL(url),1800);
}
